import {test} from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import {PDFDocument,StandardFonts} from 'pdf-lib'
import fontkit from 'pdf-fontkit'
import {getDocument} from 'pdfjs-dist/legacy/build/pdf.mjs'
import {Document,Paragraph,TextRun,Packer} from 'docx'
import {unzipSync} from 'fflate'
import {pageRange,pdfPageSize,renderScale,checkedZip} from '../src-tauri/builtin-tools/src/pdf-plan.js'
import {layoutDocument} from '../src-tauri/builtin-tools/src/pdf-layout.js'
test('page selection preserves explicit ordering, deduplicates and enforces limits',()=>{
 assert.deepEqual(pageRange('3,1-2,3',5),[2,0,1]);assert.deepEqual(pageRange('',3),[0,1,2])
 for(const value of ['0','6','4-2','1-','a','1,,2'])assert.throws(()=>pageRange(value,5))
 assert.throws(()=>pageRange('',201));assert.deepEqual(pageRange('201',201),[200])
})
test('page sizing centers an image without distortion; rendering clamps large pages',()=>{
 const page=pdfPageSize(1600,900,'a4','auto',24);assert.ok(page.width>page.height);assert.ok(Math.abs(page.imageWidth/page.imageHeight-16/9)<1e-9);assert.ok(page.x>=24)
 for(const args of [['bad','auto',24],['a4','bad',24],['a4','auto',99]])assert.throws(()=>pdfPageSize(10,20,...args))
 const scale=renderScale(2000,2000,300);assert.ok(4000000*scale*scale<=16000001)
})
test('Chinese text is embedded, paginated and extractable with the real PDF parser',async()=>{
 const pdf=await PDFDocument.create();pdf.registerFontkit(fontkit);const font=await pdf.embedFont(fs.readFileSync('src-tauri/builtin-tools/generated/media-assets/cjk-regular.ttf'),{subset:true})
 const layout=await layoutDocument(pdf,font,[{kind:'paragraph',level:1,runs:[{text:'你好，流萤百宝箱',bold:true}]},...Array.from({length:60},(_,i)=>({kind:'paragraph',text:`段落 ${i+1}：中文与 English 文档排版。`})),{kind:'table',rows:[['姓名','年龄'],['小明','18']]}])
 assert.ok(layout.pages>=2);const bytes=await pdf.save(),task=getDocument({data:bytes.slice(),useWorkerFetch:false}),loaded=await task.promise
 try{const text=(await loaded.getPage(1).then(page=>page.getTextContent())).items.map(item=>item.str??'').join('');assert.ok(text.includes('你好'));assert.ok(text.includes('流萤百宝箱'));assert.equal(loaded.numPages,layout.pages)}finally{await task.destroy()}
})
test('PDF merge copies selected pages in file/page order without rasterizing',async()=>{
 const source=await PDFDocument.create(),font=await source.embedFont(StandardFonts.Helvetica)
 for(const text of ['first','second','third'])source.addPage().drawText(text,{font,size:20})
 const target=await PDFDocument.create();for(const page of await target.copyPages(source,pageRange('3,1',3)))target.addPage(page)
 const task=getDocument({data:await target.save(),useWorkerFetch:false}),parsed=await task.promise
 try{const first=await(await parsed.getPage(1)).getTextContent();assert.ok(first.items.some(item=>item.str==='third'));assert.equal(parsed.numPages,2)}finally{await task.destroy()}
})
test('DOCX generated by the actual writer has editable Unicode text and safe ZIP limits',async()=>{
 const bytes=await Packer.toBuffer(new Document({sections:[{children:[new Paragraph({children:[new TextRun('中文文档 PDF 转换')]}),new Paragraph('second')]}]})),parts=checkedZip(bytes,unzipSync)
 assert.ok(new TextDecoder().decode(parts['word/document.xml']).includes('中文文档'))
 assert.throws(()=>checkedZip(new Uint8Array(),(_bytes,{filter})=>{filter({originalSize:33*1048576});return {}}))
})
